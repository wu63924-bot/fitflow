import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';

const moduleUrl = source => `data:text/javascript;base64,${Buffer.from(stripTypeScriptTypes(source)).toString('base64')}`;
const nutritionUrl = moduleUrl(readFileSync(new URL('../src/utils/nutrition.ts', import.meta.url), 'utf8'));
const nutrition = await import(nutritionUrl);
const { builtinFoods } = await import(moduleUrl(readFileSync(new URL('../src/data/foodCatalog.ts', import.meta.url), 'utf8')));
const recognitionSource = readFileSync(new URL('../src/services/foodRecognitionService.ts', import.meta.url), 'utf8').replaceAll('import.meta.env', '({ DEV: false })');
const { recognizeFood, MockFoodRecognitionProvider, createAiMealItem } = await import(moduleUrl(recognitionSource));
const image = new Blob(['local test image'], { type: 'image/jpeg' });
const result = await recognizeFood(image);
assert.equal(result.foods.length, 3);
assert(result.foods.some(row => row.confidence < 0.7));
const items = result.foods.map(createAiMealItem);
assert.equal(nutrition.sumItems(items).calories, 595);
const egg = builtinFoods.find(food => food.id === 'food-egg');
const eggItem = nutrition.createMealItemInGrams(egg, 100, 'stable-draft');
assert.equal(egg.servingUnit, '个');
assert.equal(eggItem.unit, 'g');
assert.equal(eggItem.id, 'stable-draft');
assert.equal(nutrition.calculateMealItem(eggItem).calories, 143);
assert.equal(nutrition.calculateMealItem(nutrition.withAmount(eggItem, 50)).calories, 71.5);
egg.calories = 999;
assert.equal(nutrition.calculateMealItem(eggItem).calories, 143);
for (const grams of [0, -1, NaN, Infinity, 10001]) assert.throws(() => nutrition.createMealItemInGrams(egg, grams));
assert.throws(() => nutrition.createMealItemInGrams(builtinFoods.find(food => food.id === 'food-milk'), 100), /毫升/);
await assert.rejects(() => recognizeFood(image, { recognizeFood: async () => ({ foods: [] }) }), /没有识别到/);
await assert.rejects(() => recognizeFood(image, { recognizeFood: async () => { throw new Error('模拟识别失败'); } }), /模拟识别失败/);
await assert.rejects(() => new MockFoodRecognitionProvider().recognizeFood(new Blob()), /照片为空/);
const backupSource = readFileSync(new URL('../src/services/backupService.ts', import.meta.url), 'utf8');
const parser = backupSource.slice(backupSource.indexOf('export function parseBackup'), backupSource.indexOf('export async function restoreBackup')) + backupSource.slice(backupSource.indexOf('function isTrainingPlan'));
const { parseBackup } = await import(moduleUrl(`import { migrateMealRecord } from '${nutritionUrl}'; const builtinFoods = ${JSON.stringify(builtinFoods)}; ${parser}`));
const backup = { version: 3, app: 'FitFlow', exportedAt: '', data: { trainingPlans: [], exercises: [], workoutSessions: [], dailySchedules: [], meals: [{ id: 'photo-meal', date: '2026-10-03', type: 'lunch', title: '午餐', createdAt: 1, updatedAt: 1, items }], foods: builtinFoods, favoriteFoods: [], recentFoods: [], bodyRecords: [], nutritionTarget: { id: 'current', calories: 2400, protein: 150, carbs: 300, fat: 65 }, settings: { id: 'app', trainingSettings: {}, user: {} } } };
assert.equal(JSON.stringify(parseBackup(JSON.stringify(backup)).data.meals[0].items), JSON.stringify(items));
const legacy = { ...backup, version: 1, data: { ...backup.data, meals: [{ id: 'old-meal', date: '2026-10-02', items: [{ id: 'old-food', name: '米饭', amount: 100, unit: 'g', calories: 130, protein: 2.7, carbs: 28, fat: 0.3 }] }] } };
assert.equal(nutrition.sumItems(parseBackup(JSON.stringify(legacy)).data.meals[0].items).calories, 130);
console.log('Phase 6A: Mock failures, gram conversion, recalculation, snapshots, validation and v1/v3 backup parsing PASS');

const compound = { ...result.foods[1], name: '未知复合菜品', estimatedGrams: 180, calories: 320, protein: 25, carbs: 20, fat: 15 };
const aiItem = createAiMealItem(compound);
assert.equal(aiItem.nutritionSource, 'ai'); assert.equal(aiItem.nutritionSnapshot.referenceAmount, 180);
assert.equal(aiItem.foodNameSnapshot, '未知复合菜品'); assert.equal(nutrition.calculateMealItem(aiItem).calories, 320);
assert.equal(nutrition.calculateMealItem(nutrition.withAmount(aiItem, 90)).calories, 160);
compound.calories = 999; assert.equal(aiItem.nutritionSnapshot.calories, 320);
for (const key of ['calories','protein','carbs','fat']) for (const value of [-1, NaN, Infinity, 10001]) assert.throws(() => createAiMealItem({ ...compound, [key]: value }), /营养值/);
for (const estimatedGrams of [0,-1,NaN,Infinity,10001]) assert.throws(() => createAiMealItem({ ...compound, estimatedGrams }), /重量/);
for (const name of ['', ' ', 'x'.repeat(61)]) assert.throws(() => createAiMealItem({ ...compound, name }), /名称/);
assert.equal(nutrition.calculateMealItem(createAiMealItem({ ...compound, calories: 0 })).calories, 0);
backup.data.meals[0].items = [aiItem];
assert.deepEqual(parseBackup(JSON.stringify(backup)).data.meals[0].items[0], aiItem);
const invalidSource = structuredClone(backup); invalidSource.data.meals[0].items[0].nutritionSource = 'unknown';
assert.throws(() => parseBackup(JSON.stringify(invalidSource)), /备份内容/);
assert(!recognitionSource.includes('foodRepository')); assert(!recognitionSource.includes('foodMatcher'));
console.log('AI totals, compound dishes without catalog, edits, immutable snapshots, source metadata and backup compatibility PASS');
